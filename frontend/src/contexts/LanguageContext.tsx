const LanguageContext = createContext<any>(undefined);

export type Language = keyof typeof translations;

export function getStoredLanguage(): Language {
  try {
    return localStorage.getItem("opticus_language") === "pt" ? "pt" : "en";
  } catch {
    return "en";
  }
}

export function translate(key: string, language: Language = getStoredLanguage()) {
  return translations[language][key] ?? translations.en[key] ?? key;
}

const problemKeys = new Map([
  [400, "api-bad-request"], [401, "api-unauthorized"], [403, "api-forbidden"],
  [404, "api-not-found"], [409, "api-conflict"], [422, "api-validation"],
  [429, "api-rate-limit"], [500, "api-internal-error"], [503, "api-service-unavailable"],
]);
const problemTypes = new Set(problemKeys.values());

export const roleKey = (role: string) =>
  role === "client" || role === "factory" || role === "staff" ? `role-${role}` : "role-unknown";

export function localizeProblem(problem: ProblemDetails, language: Language = getStoredLanguage()) {
  // Preserve payment guidance where retrying might duplicate a charge.
  const detail = typeof problem.detail === "string" ? problem.detail : "";
  if (problem.status === 400 && detail === "Email ou senha incorretos.") return translate("auth-login-invalid", language);
  if (problem.status === 409 && detail === "Já existe uma conta com esse email.") return translate("auth-account-exists", language);
  if (problem.status === 409 && (
    detail === "Os pedidos mudaram enquanto a cobrança era criada. Atualize seus pedidos antes de pagar."
    || detail === "O pedido mudou enquanto a cobrança era criada. Atualize seus pedidos antes de pagar."
  )) return translate("api-payment-conflict", language);
  if (detail.startsWith("Não foi possível confirmar a cobrança com o gateway de pagamento.")) {
    return translate("api-payment-pending", language);
  }
  if (detail.startsWith("O pagamento está indisponível no momento. Nenhuma cobrança foi criada")) {
    return translate("api-payment-unavailable", language);
  }
  const type = typeof problem.type === "string"
    ? problem.type.match(/^https:\/\/opticus\.example\/problems\/([a-z-]+)$/)?.[1]
    : undefined;
  const key = `api-${type}`;
  return translate(problemTypes.has(key) ? key : problemKeys.get(problem.status) ?? "api-unknown", language);
}

export function LanguageProvider({ children }) {
  const [language, setLangState] = useState(getStoredLanguage);

  const setLanguage = (lang) => {
    if (lang === "en" || lang === "pt") {
      setLangState(lang);
      localStorage.setItem("opticus_language", lang);
    }
  };

  const t = (key) => {
    return translate(key, language);
  };

  useEffect(() => {
    document.documentElement.lang = language === "pt" ? "pt-BR" : "en";
  }, [language]);

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useTranslation() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useTranslation must be used within a LanguageProvider");
  }
  return context;
}
